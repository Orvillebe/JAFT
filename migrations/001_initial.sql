-- =====================
-- Row Level Security
-- =====================
-- Everyone who is logged in sees and edits all data (shared work, no roles yet).
-- Deleting rows is only needed for undo right after saving and for emptying the bin.
-- Stages and stage changes are never deleted.

alter table members enable row level security;
alter table companies enable row level security;
alter table persons enable row level security;
alter table history_entries enable row level security;
alter table stages enable row level security;
alter table stage_changes enable row level security;
alter table week_actions enable row level security;
alter table app_settings enable row level security;
alter table schema_migrations enable row level security;

create policy "read members" on members for select to authenticated using (true);
create policy "update own member" on members for update to authenticated using (id = auth.uid());
create policy "insert own member" on members for insert to authenticated with check (id = auth.uid());

create policy "read companies" on companies for select to authenticated using (true);
create policy "insert companies" on companies for insert to authenticated with check (true);
create policy "update companies" on companies for update to authenticated using (true) with check (true);
create policy "delete companies" on companies for delete to authenticated using (true);

create policy "read persons" on persons for select to authenticated using (true);
create policy "insert persons" on persons for insert to authenticated with check (true);
create policy "update persons" on persons for update to authenticated using (true) with check (true);
create policy "delete persons" on persons for delete to authenticated using (true);

create policy "read history" on history_entries for select to authenticated using (true);
create policy "insert history" on history_entries for insert to authenticated with check (true);
create policy "update history" on history_entries for update to authenticated using (true) with check (true);
create policy "delete history" on history_entries for delete to authenticated using (true);

create policy "read stages" on stages for select to authenticated using (true);
create policy "insert middle stages" on stages for insert to authenticated with check (kind = 'middle');
create policy "update stages" on stages for update to authenticated using (true) with check (true);

create policy "read stage changes" on stage_changes for select to authenticated using (true);
-- The fixed stages can never be archived.
create policy "insert stage changes" on stage_changes for insert to authenticated
  with check (stage_id not in ('contact', 'order'));

create policy "read week actions" on week_actions for select to authenticated using (true);
create policy "insert week actions" on week_actions for insert to authenticated with check (created_by = auth.uid());
create policy "delete own week actions" on week_actions for delete to authenticated using (created_by = auth.uid());

create policy "read settings" on app_settings for select to authenticated using (true);
create policy "insert settings" on app_settings for insert to authenticated with check (true);
create policy "update settings" on app_settings for update to authenticated using (true) with check (true);

-- Only migrations write here (they run as the database owner in the SQL Editor).
create policy "read migrations" on schema_migrations for select to authenticated using (true);

