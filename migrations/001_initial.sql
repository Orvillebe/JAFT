-- JAFT migration 001: the initial schema, for its own Supabase project (not the JATL project).
--
-- Migrations run once each, in number order, in the SQL Editor. Never edit a migration that has run:
-- a later change is a new file (002_..., 003_...). Each file records itself in schema_migrations,
-- and the app checks that number at startup (version.js). Rules: docs/design.md, "Versions and changes".
-- Run this one in a new, empty project. See README for the full setup.
-- Design: docs/design.md. In short:
--   members          users, linked to Supabase Auth (registration off, users are invited)
--   companies        companies; archived together with their persons, or binned when empty
--   persons          contact persons and contacts; a person is a contact once it has a first-contact entry
--   history_entries  one row per save; a person's stage, status, next step and amount are derived from these
--   stages           Contact (fixed), middle stages (managed in Instellingen), Opdracht (fixed)
--   stage_changes    when a middle stage was archived or restored (the overview needs the dates)
--   week_actions     one row per tap on events (+1/-1) or the LinkedIn post (1/0), by date
--   app_settings     shared settings changed in Instellingen (for now: the first day of the week)
--   schema_migrations which migrations have run
--
-- Ids are generated by the app (UUIDs as text), so a save and its undo never wait for the server.
-- created_by/at are filled in here; changed_by/at by a trigger. Nothing is ever identified by a name.

-- =====================
-- Members
-- =====================

create table members (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text,
  created_at timestamptz not null default now()
);

-- A profile is created when an invited user is created.
create or replace function handle_new_user()
returns trigger as $$
begin
  insert into public.members (id, name, email)
  values (new.id, coalesce(new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)), new.email);
  return new;
end;
$$ language plpgsql security definer set search_path = public;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function handle_new_user();

