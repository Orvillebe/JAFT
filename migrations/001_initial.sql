create table companies (
  id text primary key default gen_random_uuid()::text,
  name text not null check (btrim(name) <> ''),
  phone text not null default '',
  email text not null default '',
  website text not null default '',
  note text not null default '',
  archived_at timestamptz,
  archive_group text,
  deleted_at timestamptz,
  created_by uuid default auth.uid() references members(id) on delete set null,
  created_at timestamptz not null default clock_timestamp(),
  changed_by uuid references members(id) on delete set null,
  changed_at timestamptz
);

create table persons (
  id text primary key default gen_random_uuid()::text,
  company_id text references companies(id) on delete set null,
  name text not null check (btrim(name) <> ''),
  phone text not null default '',
  email text not null default '',
  job_title text not null default '',
  archived_at timestamptz,
  archive_group text,
  deleted_at timestamptz,
  created_by uuid default auth.uid() references members(id) on delete set null,
  created_at timestamptz not null default clock_timestamp(),
  changed_by uuid references members(id) on delete set null,
  changed_at timestamptz
);
create index persons_company on persons (company_id);
create index persons_archive_group on persons (archive_group) where archive_group is not null;

create table stages (
  id text primary key default gen_random_uuid()::text,
  kind text not null check (kind in ('start', 'middle', 'end')),
  name text,                            -- null for the fixed stages: their label comes from the translation file
  position integer not null,
  created_by uuid default auth.uid() references members(id) on delete set null,
  created_at timestamptz not null default clock_timestamp(),
  changed_by uuid references members(id) on delete set null,
  changed_at timestamptz,
  check (kind = 'middle' or name is null),
  check (kind <> 'middle' or btrim(coalesce(name, '')) <> '')
);
-- Exactly one start stage and one end stage, with fixed ids.
create unique index stages_one_start on stages (kind) where kind in ('start', 'end');

create table stage_changes (
  id text primary key default gen_random_uuid()::text,
  stage_id text not null references stages(id),
  happened_on date not null,
  change text not null check (change in ('archived', 'restored')),
  created_by uuid default auth.uid() references members(id) on delete set null,
  created_at timestamptz not null default clock_timestamp(),
  changed_by uuid references members(id) on delete set null,
  changed_at timestamptz
);

create table history_entries (
  id text primary key default gen_random_uuid()::text,
  person_id text not null references persons(id) on delete cascade,
  kind text not null check (kind in ('first_contact', 'follow_up', 'status')),
  happened_on date not null,            -- when it happened; every count uses this date
  action text not null default '',
  note text not null default '',
  stage_id text references stages(id),  -- the stage chosen in this save, if any
  amount numeric(12, 2) check (amount is null or amount >= 0),
  status text check (status in ('active', 'inactive')),
  next_step text not null default '',
  next_step_on date,
  entry_channel text,                   -- first contact only: key from config.js (hook, linkedin, cold)
  via text,                             -- first contact, hook only: key from config.js (event, referral, other)
  hook text not null default '',        -- first contact only
  deleted_at timestamptz,
  created_by uuid default auth.uid() references members(id) on delete set null,
  created_at timestamptz not null default clock_timestamp(),  -- when it was entered
  changed_by uuid references members(id) on delete set null,
  changed_at timestamptz,
  check (kind <> 'status' or status is not null),
  check (kind <> 'first_contact' or entry_channel is not null),
  check (next_step_on is null or next_step_on > happened_on)
);
-- A person has at most one first contact.
create unique index history_one_first_contact on history_entries (person_id) where kind = 'first_contact';
create index history_person on history_entries (person_id, happened_on);

create table week_actions (
  id text primary key default gen_random_uuid()::text,
  happened_on date not null,            -- a day in the week it counts for; the week is derived, never stored
  kind text not null check (kind in ('event', 'post')),
  value integer not null check ((kind = 'event' and value in (1, -1)) or (kind = 'post' and value in (0, 1))),
  created_by uuid default auth.uid() references members(id) on delete set null,
  created_at timestamptz not null default clock_timestamp(),
  changed_by uuid references members(id) on delete set null,
  changed_at timestamptz
);
create index week_actions_day on week_actions (happened_on);

-- Shared settings. One row per key; the value is JSON so a setting can be any shape.
create table app_settings (
  key text primary key,
  value jsonb not null,
  changed_by uuid default auth.uid() references members(id) on delete set null,
  changed_at timestamptz not null default now()
);

-- Which migrations have run. The app reads the highest version at startup.
create table schema_migrations (
  version integer primary key,
  name text not null,
  applied_at timestamptz not null default now()
);

-- =====================
-- Who changed it, and when
-- =====================

create or replace function set_changed()
returns trigger as $$
begin
  new.changed_by := auth.uid();
  new.changed_at := now();
  new.created_by := old.created_by;   -- creation info never changes
  new.created_at := old.created_at;
  return new;
end;
$$ language plpgsql set search_path = public;

create trigger companies_changed before update on companies for each row execute function set_changed();
create trigger persons_changed before update on persons for each row execute function set_changed();
create trigger stages_changed before update on stages for each row execute function set_changed();
create trigger history_changed before update on history_entries for each row execute function set_changed();

create or replace function set_setting_changed()
returns trigger as $$
begin
  new.changed_by := auth.uid();
  new.changed_at := now();
  return new;
end;
$$ language plpgsql set search_path = public;

create trigger settings_changed before update on app_settings for each row execute function set_setting_changed();

