-- A new contact: a new company if needed, a new person or a contact person who becomes
-- a contact, and the first-contact entry.
create or replace function create_contact(p jsonb)
returns jsonb
language plpgsql security invoker set search_path = public
as $$
declare
  c companies; pe persons; e history_entries;
begin
  if p->'company' is not null and jsonb_typeof(p->'company') = 'object' then
    insert into companies (id, name, phone, email, website, note)
    select x.id, x.name, coalesce(x.phone, ''), coalesce(x.email, ''), coalesce(x.website, ''), coalesce(x.note, '')
    from jsonb_populate_record(null::companies, p->'company') x
    returning * into c;
  end if;

  if (p->>'person_is_new')::boolean then
    insert into persons (id, company_id, name, phone, email, job_title)
    select x.id, x.company_id, x.name, coalesce(x.phone, ''), coalesce(x.email, ''), coalesce(x.job_title, '')
    from jsonb_populate_record(null::persons, p->'person') x
    returning * into pe;
  else
    update persons set
      company_id = (p->'person'->>'company_id'), name = p->'person'->>'name',
      phone = coalesce(p->'person'->>'phone', ''), email = coalesce(p->'person'->>'email', ''),
      job_title = coalesce(p->'person'->>'job_title', '')
    where id = p->'person'->>'id' and archived_at is null and deleted_at is null
    returning * into pe;
    if pe.id is null then raise exception 'Contact person % no longer exists', p->'person'->>'id'; end if;
  end if;

  insert into history_entries (id, person_id, kind, happened_on, note, stage_id, next_step, next_step_on, entry_channel, via, hook)
  select x.id, pe.id, 'first_contact', x.happened_on, coalesce(x.note, ''), 'contact', coalesce(x.next_step, ''), x.next_step_on,
         x.entry_channel, x.via, coalesce(x.hook, '')
  from jsonb_populate_record(null::history_entries, p->'entry') x
  returning * into e;

  return jsonb_build_object(
    'company', case when c.id is null then null else to_jsonb(c) end,
    'person', to_jsonb(pe),
    'entry', to_jsonb(e)
  );
end;
$$;

-- A company with everyone at it, archived together under one group.
create or replace function archive_company(company_id text, archive_group text)
returns void
language plpgsql security invoker set search_path = public
as $$
begin
  update companies set archived_at = now(), archive_group = archive_company.archive_group where id = archive_company.company_id;
  update persons set archived_at = now(), archive_group = archive_company.archive_group
   where persons.company_id = archive_company.company_id and archived_at is null and deleted_at is null;
end;
$$;

-- Everything archived together comes back together.
create or replace function restore_archive_group(archive_group text)
returns void
language plpgsql security invoker set search_path = public
as $$
begin
  update companies set archived_at = null, archive_group = null where companies.archive_group = restore_archive_group.archive_group;
  update persons set archived_at = null, archive_group = null where persons.archive_group = restore_archive_group.archive_group;
end;
$$;

